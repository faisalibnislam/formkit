export const LangContext = createContext<Lang>("en");

/** The live form's words in the language it is showing. */
export function useT() {
  const lang = useContext(LangContext);
  return (key: Key, vars?: Record<string, string | number>) => tr(lang, key, vars);
}

type BlockText = { blockId: string; title?: string; help?: string; placeholder?: string; options?: string[]; rows?: string[]; pageName?: string };
export type Translation = {
  lang: string;
  blocks: BlockText[];
  screens: { welcomeTitle?: string; welcomeMessage?: string; welcomeButton?: string; thanksTitle?: string; thanksMessage?: string; closedMessage?: string };
};

type Localizable = {
  welcome?: { title?: string | null; message?: string | null; button?: string | null } | null;
  thanks?: { title?: string | null; message?: string | null } | null;
  closedMessage?: string;
  blocks: {
    _id: string;
    title: string | null;
    help: string | null;
    placeholder: string | null;
    pageName: string | null;
    options: string[] | null;
    rows?: string[] | null;
    optionLabels?: string[] | null;
    rowLabels?: string[] | null;
  }[];
};

/**
 * The form in another language: its words swapped for the translation's,
 * where there is one. Options and rows keep their own values (that is what
 * an answer records) and gain labels to show.
 */
export function localize<T extends Localizable>(data: T, t: Translation | undefined): T {
  if (!t) return data;
  const byId = new Map(t.blocks.map((b) => [b.blockId, b]));
  const s = t.screens;
  return {
    ...data,
    welcome: data.welcome
      ? { ...data.welcome, title: s.welcomeTitle || data.welcome.title, message: s.welcomeMessage || data.welcome.message, button: s.welcomeButton || data.welcome.button }
      : data.welcome,
    thanks: data.thanks ? { ...data.thanks, title: s.thanksTitle || data.thanks.title, message: s.thanksMessage || data.thanks.message } : data.thanks,
    closedMessage: s.closedMessage || data.closedMessage,
    blocks: data.blocks.map((b) => {
      const x = byId.get(b._id);
      if (!x) return b;
      return {
        ...b,
        title: x.title || b.title,
        help: x.help || b.help,
        placeholder: x.placeholder || b.placeholder,
        pageName: x.pageName || b.pageName,
        optionLabels: x.options && b.options && x.options.length === b.options.length ? x.options : null,
        rowLabels: x.rows && b.rows && x.rows.length === b.rows.length ? x.rows : null,
      };
    }),
  };
}
