/** A phrase in a language, with its {placeholders} filled in. */
export function tr(lang: Lang | undefined, key: Key, vars: Record<string, string | number> = {}) {
  const text = (lang && lang !== "en" ? DICTS[lang]?.[key] : undefined) ?? EN[key];
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** The best of a form's languages for this visitor: the link's ?lang=, then the browser's, then the form's own. */
export function pickLang(offered: Lang[], fallback: Lang, fromLink: string | null, browser: readonly string[]): Lang {
  const want = [fromLink, ...browser].filter(Boolean).map((x) => x!.toLowerCase().slice(0, 2));
  return (want.find((w) => offered.includes(w as Lang)) as Lang | undefined) ?? fallback;
}

